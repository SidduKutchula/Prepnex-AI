/**
 * Slack Controller
 * 
 * Handles incoming webhooks from Slack:
 * 1. URL Verification Handshake (type: "url_verification")
 * 2. Events API (type: "event_callback"):
 *    - message (Direct Messages to the bot)
 *    - app_mention (@bot mentions in public/private channels)
 * 3. Slash Commands (application/x-www-form-urlencoded)
 * 4. Interactive Block Actions (button clicks)
 */

const slackClient = require("./slack.client");
const chatService = require("../../services/chat.service");
const { formatForSlack } = require("../responseAdapter");
const ChannelUserModel = require("../../models/channelUser.model");
const { parseChannelRequest } = require("../channelTypes");

/**
 * Main webhook handler for Slack events and slash commands.
 */
async function handleWebhook(req, res) {
    // 0. Ignore Slack retry attempts to prevent duplicate AI replies
    if (req.headers && req.headers["x-slack-retry-num"]) {
        console.log(`[Slack] Ignoring retry #${req.headers["x-slack-retry-num"]} (${req.headers["x-slack-retry-reason"] || "timeout"})`);
        return res.status(200).send();
    }

    const body = req.body;

    // 1. Handle URL verification challenge during Slack app setup
    if (body && body.type === "url_verification") {
        console.log("[Slack] URL verification challenge received.");
        return res.status(200).json({ challenge: body.challenge });
    }

    // 2. Handle interactive payloads (e.g. Button clicks from Block Kit)
    if (body && body.payload) {
        res.status(200).send(); // Acknowledge immediately
        handleInteractiveAction(body.payload).catch(err => {
            console.error("[Slack] Interactive action error:", err);
        });
        return;
    }

    // 3. Handle Slash Commands (e.g. /analyze, /gaps, /plan, /help, /prepnex)
    if (body && body.command) {
        res.status(200).send(); // Slack requires 200 within 3 seconds
        handleSlashCommand(body).catch(err => {
            console.error("[Slack] Slash command processing error:", err);
        });
        return;
    }

    // 4. Handle Events API callbacks
    if (body && body.type === "event_callback") {
        // Immediately acknowledge Slack (must be within 3 seconds to prevent retries)
        res.status(200).send();

        // Process event asynchronously in background
        processSlackEvent(body.event).catch(err => {
            console.error("[Slack] Event processing error:", err);
        });
        return;
    }

    // Unhandled type
    return res.status(200).send();
}

/**
 * Process Slack Events (message or app_mention).
 */
async function processSlackEvent(event) {
    if (!event) return;

    // Prevent bot-to-bot loops: ignore messages generated by bots
    if (event.bot_id || event.subtype === "bot_message" || event.subtype === "message_changed") {
        return;
    }

    // Only handle DMs (channel_type === "im" or channel ID starts with "D") or app mentions
    const isDirectMessage = event.channel_type === "im" || (typeof event.channel === "string" && event.channel.startsWith("D"));
    const isAppMention = event.type === "app_mention";

    // Prevent ambient channel chatter: only respond to direct DMs or explicit @bot mentions
    if (!isDirectMessage && !isAppMention) {
        return;
    }

    const userId = event.user;
    const channelId = event.channel;
    const threadTs = event.thread_ts || event.ts; // Maintain thread context

    let text = event.text || "";
    // Clean app mention prefix (e.g. "<@U12345678> analyze my resume" -> "analyze my resume")
    text = text.replace(/<@[A-Z0-9]+>/g, "").trim();

    // Check for file attachments (e.g. uploaded resume PDF)
    const attachments = [];
    if (event.files && event.files.length > 0) {
        for (const file of event.files) {
            const isPdf = file.mimetype === "application/pdf" || (file.name && file.name.endsWith(".pdf"));
            if (isPdf) {
                const downloadUrl = file.url_private_download || file.url_private;
                if (downloadUrl) {
                    try {
                        console.log(`[Slack] Downloading uploaded PDF: ${file.name}`);
                        const buffer = await slackClient.downloadFile(downloadUrl);
                        attachments.push({
                            type: "document",
                            mimeType: "application/pdf",
                            buffer,
                            fileName: file.name || "resume.pdf",
                        });
                    } catch (err) {
                        console.error("[Slack] Failed to download Slack file:", err.message);
                        attachments.push({
                            type: "document",
                            mimeType: "application/pdf",
                            fileName: file.name || "resume.pdf",
                        });
                    }
                }
            }
        }
    }

    if (!text && attachments.length === 0) {
        return;
    }

    // Resolve user display name
    const userInfo = await slackClient.getUserInfo(userId);
    const displayName = userInfo?.displayName || null;

    // 1. Resolve or create user mapping
    const channelUser = await ChannelUserModel.findOrCreateByExternalId(
        "slack",
        userId,
        displayName
    );

    // 2. Build channel-independent request shape
    const channelRequest = parseChannelRequest({
        channel: "slack",
        userId: String(channelUser.userId),
        threadId: threadTs,
        message: text || "Please parse my uploaded resume.",
        attachments,
    });

    // 3. Call central conversational orchestrator
    const channelResponse = await chatService.processMessage(channelRequest);

    // 4. Format for Slack Block Kit
    const formatted = formatForSlack(channelResponse);

    // 5. Reply back in thread or channel
    await slackClient.postMessage({
        channel: channelId,
        text: formatted.text,
        blocks: formatted.blocks,
        thread_ts: threadTs,
    });
}

/**
 * Handle Slash Command invocations (e.g., /analyze, /gaps, /prepnex).
 */
async function handleSlashCommand(body) {
    const userId = body.user_id;
    const channelId = body.channel_id;
    const command = body.command;
    const text = (body.text || "").trim();

    // Reconstruct the user's intent as command + query text
    let fullMessage;
    if (command === "/prepnex") {
        if (!text) {
            fullMessage = "/help";
        } else if (text.startsWith("/")) {
            fullMessage = text;
        } else {
            // Check if user typed a known command word like "help", "build", "analyze"
            const firstWord = text.split(" ")[0].toLowerCase();
            const knownCommands = ["help", "analyze", "gaps", "plan", "quiz", "mock", "ready", "build", "builder"];
            if (knownCommands.includes(firstWord)) {
                fullMessage = `/${text}`;
            } else {
                fullMessage = text;
            }
        }
    } else {
        fullMessage = text ? `${command} ${text}` : command;
    }

    const channelUser = await ChannelUserModel.findOrCreateByExternalId(
        "slack",
        userId,
        body.user_name || null
    );

    const channelRequest = parseChannelRequest({
        channel: "slack",
        userId: String(channelUser.userId),
        message: fullMessage,
        attachments: [],
    });

    const channelResponse = await chatService.processMessage(channelRequest);
    const formatted = formatForSlack(channelResponse);

    // If Slack provided a response_url, use it for immediate in_channel delivery
    if (body.response_url) {
        try {
            const resp = await fetch(body.response_url, {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify({
                    text: formatted.text,
                    blocks: formatted.blocks,
                    response_type: "in_channel",
                }),
            });
            if (resp.ok) return;
        } catch (err) {
            console.warn("[Slack] response_url failed, falling back to postMessage:", err.message);
        }
    }

    await slackClient.postMessage({
        channel: channelId,
        text: formatted.text,
        blocks: formatted.blocks,
    });
}

/**
 * Handle interactive button clicks from Block Kit.
 */
async function handleInteractiveAction(rawPayload) {
    let payload;
    try {
        payload = typeof rawPayload === "string" ? JSON.parse(rawPayload) : rawPayload;
    } catch {
        return;
    }

    if (payload.type !== "block_actions") return;

    const action = payload.actions?.[0];
    if (!action) return;

    const userId = payload.user?.id;
    const channelId = payload.channel?.id;
    const threadTs = payload.message?.thread_ts || payload.message?.ts;
    const actionValue = action.value || action.text?.text;

    if (!actionValue) return;

    const channelUser = await ChannelUserModel.findOrCreateByExternalId(
        "slack",
        userId,
        payload.user?.name || null
    );

    const channelRequest = parseChannelRequest({
        channel: "slack",
        userId: String(channelUser.userId),
        threadId: threadTs,
        message: actionValue,
        attachments: [],
    });

    const channelResponse = await chatService.processMessage(channelRequest);
    const formatted = formatForSlack(channelResponse);

    await slackClient.postMessage({
        channel: channelId,
        text: formatted.text,
        blocks: formatted.blocks,
        thread_ts: threadTs,
    });
}

module.exports = {
    handleWebhook,
    processSlackEvent,
    handleSlashCommand,
    handleInteractiveAction,
};
